package com.experiment.productservice.contract;

import au.com.dius.pact.provider.junit5.HttpTestTarget;
import au.com.dius.pact.provider.junit5.PactVerificationContext;
import au.com.dius.pact.provider.junit5.PactVerificationInvocationContextProvider;
import au.com.dius.pact.provider.junitsupport.Provider;
import au.com.dius.pact.provider.junitsupport.State;
import au.com.dius.pact.provider.junitsupport.loader.PactFolder;
import com.experiment.productservice.model.Product;
import com.experiment.productservice.repository.ProductRepository;
import org.junit.jupiter.api.*;
import org.junit.jupiter.api.extension.ExtendWith;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.server.LocalServerPort;
import org.springframework.test.context.ActiveProfiles;

import java.math.BigDecimal;

/**
 * ─────────────────────────────────────────────────────────────────
 * CONTRACT TESTS (PROVIDER)  –  ProductContractVerifierTest
 * ─────────────────────────────────────────────────────────────────
 * Testing Level : Contract (Provider / Verifier side)
 * Framework     : Pact JVM (Provider Verification)
 *
 * HOW IT WORKS:
 *  1. This test starts the real Product Service on a random port.
 *  2. Pact loads the contract files (.json) from target/pacts/
 *     (generated by the consumer's ProductConsumerPactTest).
 *  3. For each interaction in the pact file, Pact:
 *       a) Calls the @State method to set up pre-conditions in the DB.
 *       b) Sends the exact HTTP request the consumer defined.
 *       c) Verifies the response matches the consumer's expectations.
 *
 *  The @PactFolder points to where the CI pipeline copied the pact
 *  JSON files after running the consumer tests.
 * ─────────────────────────────────────────────────────────────────
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@ActiveProfiles("test")   // H2 database for contract verification
@Provider("product-service")
@PactFolder("target/pacts")
@DisplayName("Contract Tests (Provider) – Product Service verifies consumer pacts")
class ProductContractVerifierTest {

    @LocalServerPort
    private int serverPort;

    @Autowired
    private ProductRepository productRepository;

    // ── Test Lifecycle ────────────────────────────────────────────────────

    @BeforeEach
    void setUpTarget(PactVerificationContext context) {
        // Point Pact at our running server
        context.setTarget(new HttpTestTarget("localhost", serverPort));
    }

    @AfterEach
    void cleanUp() {
        productRepository.deleteAll();
    }

    // ── Pact Verification Entry Point ─────────────────────────────────────

    /**
     * JUnit 5 extension that replays each interaction from the pact file
     * and verifies the provider's response matches.
     */
    @TestTemplate
    @ExtendWith(PactVerificationInvocationContextProvider.class)
    @DisplayName("Verifying Pact interaction")
    void verifyPactInteraction(PactVerificationContext context) {
        context.verifyInteraction();
    }

    // ── Provider State Setup ──────────────────────────────────────────────
    // Each @State method is called by Pact before replaying the matching
    // consumer interaction, allowing us to seed the database.

    /**
     * State: "products exist"
     * Satisfies: GET /api/products → non-empty list
     */
    @State("products exist")
    void productsExistState() {
        productRepository.deleteAll();
        productRepository.save(
                new Product("Laptop", new BigDecimal("999.99"), "Electronics", 50));
        productRepository.save(
                new Product("Headphones", new BigDecimal("149.99"), "Electronics", 200));
    }

    /**
     * State: "product with id 1 exists"
     * Satisfies: GET /api/products/1 → single product response
     *
     * Note: We cannot guarantee the auto-generated id will be 1, so we
     * save with a known name and rely on Pact's type-matching (not value
     * matching) for the id field in the consumer pact definition.
     */
    @State("product with id 1 exists")
    void productWithId1ExistsState() {
        productRepository.deleteAll();

        // Insert in a way that the auto-increment id starts fresh at 1
        // (H2 resets sequences after deleteAll on a fresh schema)
        Product laptop = new Product("Laptop", new BigDecimal("999.99"), "Electronics", 50);
        productRepository.save(laptop);
    }

    /**
     * State: "product with id 9999 does not exist"
     * Satisfies: GET /api/products/9999 → 404 response
     */
    @State("product with id 9999 does not exist")
    void productWithId9999DoesNotExistState() {
        productRepository.deleteAll();
        // No products saved → id 9999 definitely doesn't exist
    }

    /**
     * State: "electronics products exist"
     * Satisfies: GET /api/products/category/Electronics → filtered list
     */
    @State("electronics products exist")
    void electronicsProductsExistState() {
        productRepository.deleteAll();
        productRepository.save(
                new Product("Laptop",     new BigDecimal("999.99"),  "Electronics", 50));
        productRepository.save(
                new Product("Tablet",     new BigDecimal("499.99"),  "Electronics", 30));
        productRepository.save(
                new Product("Headphones", new BigDecimal("149.99"),  "Electronics", 200));
    }
}
